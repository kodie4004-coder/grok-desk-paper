// One pass over the frozen P1–P3 rules. No retune.
import fs from 'node:fs';
import zlib from 'node:zlib';
import { PREDICT_RULES, feeRate, resolutionPnl } from '../engine/predict.js';
import { graduates } from '../engine/strategies.js';
import { clusterBootstrap } from '../engine/eval.js';

const file = process.argv[2] || 'runner/research/predict-markets.json.gz';
const data = JSON.parse(zlib.gunzipSync(fs.readFileSync(file)).toString('utf8'));
const markets = data.markets || [];

function weekKey(t) {
  const d = new Date(t);
  const onejan = new Date(Date.UTC(d.getUTCFullYear(), 0, 1));
  const week = Math.floor((d - onejan) / 604800000);
  return `${d.getUTCFullYear()}-W${week}`;
}

function tradesFor(rule) {
  const out = [];
  for (const m of markets) {
    const quote = rule.id === 'p3' ? m.late : m.week;
    if (!quote || !m.conditionId) continue;
    const picked = rule.pick(quote.yes);
    if (!picked) continue;
    const won = picked.side === 'yes' ? m.yesWon === true : m.yesWon === false;
    const r = resolutionPnl(picked.price, won, feeRate(m));
    out.push({
      pool: m.conditionId,
      pnl: r.perDollar,
      dollars: r.pnl,
      week: weekKey(m.end),
      question: m.question,
    });
  }
  return out;
}

function byWeek(trades) {
  const map = new Map();
  for (const t of trades) {
    if (!map.has(t.week)) map.set(t.week, []);
    map.get(t.week).push(t);
  }
  return [...map.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([week, rows]) => {
    const boot = clusterBootstrap(rows, { iters: 2000, seed: 7 });
    const mean = rows.reduce((a, t) => a + t.pnl, 0) / rows.length;
    return { week, seen: false, n: rows.length, nPools: new Set(rows.map((t) => t.pool)).size, mean, lo: boot.lo, hi: boot.hi };
  });
}

const lines = ['# Prediction-market paper study', '', 'Play money is not in this table. Kalshi did not answer, so P4 was not run. Expectancy is profit per $1 of entry cost after the taker fee and a 0.005 haircut.', ''];
const priorRows = [];
let any = false;
for (const rule of PREDICT_RULES) {
  const weeks = byWeek(tradesFor(rule));
  const pass = graduates(weeks);
  if (pass) any = true;
  lines.push(`## ${rule.id} ${rule.label}`);
  lines.push('');
  lines.push('| Week | Trades | Mean per $1 | 90% low | 90% high |');
  lines.push('|---|---:|---:|---:|---:|');
  for (const w of weeks) lines.push(`| ${w.week} | ${w.n} | ${w.mean.toFixed(3)} | ${w.lo == null ? '—' : w.lo.toFixed(3)} | ${w.hi == null ? '—' : w.hi.toFixed(3)} |`);
  if (!weeks.length) lines.push('| none | 0 | — | — | — |');
  lines.push('');
  lines.push(`Graduates: ${pass ? 'yes' : 'no'}.`);
  lines.push('');
  const usable = weeks.filter((w) => w.n >= 20);
  const avg = usable.length ? usable.reduce((a, w) => a + w.mean, 0) / usable.length : null;
  priorRows.push({ id: rule.id, label: rule.label, n: weeks.reduce((a, w) => a + w.n, 0), mean: avg, lo: usable.length ? Math.min(...usable.map((w) => w.lo)) : null, hi: usable.length ? Math.max(...usable.map((w) => w.hi)) : null, windows: usable.length, graduated: pass });
}
lines.push(any ? 'At least one rule cleared every usable week.' : 'No prediction rule graduated. They stay at exploration size.');
fs.writeFileSync('PREDICT_REPORT.md', lines.join('\n'));
const prior = {
  id: 'predict-v4',
  collectedAt: data.collectedAt || null,
  summary: any
    ? 'A pre-registered prediction rule was positive on every week with 20 trades. That rule can use the normal paper size.'
    : 'No pre-registered prediction rule was positive across three or more weeks. They stay at 1% exploration size. Kalshi was not tested. Manifold is play money and is not in this verdict.',
  edges: Object.fromEntries(priorRows.map((r) => [r.id, r.graduated])),
  rows: priorRows,
  kalshi: 'unavailable',
};
fs.writeFileSync('engine/predict-prior.js', `// Generated by runner/study-predict.mjs. Do not hand-edit the verdict.\nexport const PREDICT_PRIOR = ${JSON.stringify(prior, null, 2)};\n`);
