// One pass over the frozen C1–C3 rules. Hourly bars, 0.30% primary cost.
import fs from 'node:fs';
import zlib from 'node:zlib';
import { PROTOCOL, simulateTrades, clusterBootstrap } from '../engine/eval.js';
import { MAJOR_RULES, MAJOR_FEE, isMajor } from '../engine/majors.js';
import { roundTripImpactPct } from '../engine/core.js';
import { graduates } from '../engine/strategies.js';

const file = process.argv[2] || 'runner/research/majors-hourly.json.gz';
const data = JSON.parse(zlib.gunzipSync(fs.readFileSync(file)).toString('utf8'));
const pools = (data.pools || []).filter((p) => isMajor(p) && p.bars && p.bars.length > 80);
const WEEK = 7 * 86400000;
const tMax = Math.max(...pools.map((p) => p.bars.at(-1).t));
const tMin = Math.min(...pools.map((p) => p.bars[0].t));
const blocks = [];
for (let end = tMax; end - WEEK >= tMin; end -= WEEK) blocks.push({ start: end - WEEK, end, seen: false });
blocks.reverse();

function run(rule, feePct, start, end) {
  const all = [];
  for (const p of [...pools].sort((a, b) => String(a.pool).localeCompare(String(b.pool)))) {
    const fee = feePct + roundTripImpactPct(25, p.liq || 0);
    const cfg = { ...PROTOCOL, feePct: fee, sizeUsd: 25, fill: 'conservative', tradeFrom: start, tradeTo: end, maxEntryGapMs: 2 * 3600000, cooldownMs: 24 * 3600000 };
    for (const tr of simulateTrades(p.bars, rule.plan, cfg)) all.push({ ...tr, pool: p.pool, feePct: fee });
  }
  const boot = clusterBootstrap(all, { iters: 2000, seed: 7 });
  const mean = all.length ? all.reduce((a, t) => a + t.pnl, 0) / all.length : 0;
  return { n: all.length, nPools: new Set(all.map((t) => t.pool)).size, mean, lo: boot.lo, hi: boot.hi, seen: false };
}

const lines = ['# Liquid majors paper study', '', `Pools ${pools.length}. Primary cost 0.30% round trip plus impact. The 1% column is a stress test and cannot graduate a rule. Hourly bars use a 2-hour entry gap because the next bar is an hour away.`, ''];
const priorRows = [];
let any = false;
for (const rule of MAJOR_RULES) {
  const primary = blocks.map((b) => ({ ...b, ...run(rule, MAJOR_FEE, b.start, b.end) }));
  const stress = blocks.map((b) => run(rule, 1, b.start, b.end));
  const pass = graduates(primary);
  if (pass) any = true;
  lines.push(`## ${rule.id} ${rule.label}`);
  lines.push('');
  lines.push('| Week ending | Trades | Mean at 0.30% | 90% low | 90% high | Mean at 1% |');
  lines.push('|---|---:|---:|---:|---:|---:|');
  primary.forEach((w, i) => {
    const when = new Date(w.end).toISOString().slice(0, 10);
    lines.push(`| ${when} | ${w.n} | ${w.mean.toFixed(2)} | ${w.lo == null ? '—' : w.lo.toFixed(2)} | ${w.hi == null ? '—' : w.hi.toFixed(2)} | ${stress[i].mean.toFixed(2)} |`);
  });
  lines.push('');
  lines.push(`Graduates at 0.30%: ${pass ? 'yes' : 'no'}.`);
  lines.push('');
  const usable = primary.filter((w) => w.n >= 20);
  const all = [];
  for (const p of [...pools].sort((a, b) => String(a.pool).localeCompare(String(b.pool)))) {
    const fee = MAJOR_FEE + roundTripImpactPct(25, p.liq || 0);
    const cfg = { ...PROTOCOL, feePct: fee, sizeUsd: 25, fill: 'conservative', maxEntryGapMs: 2 * 3600000, cooldownMs: 24 * 3600000 };
    for (const tr of simulateTrades(p.bars, rule.plan, cfg)) all.push({ ...tr, pool: p.pool });
  }
  const boot = clusterBootstrap(all, { iters: 2000, seed: 7 });
  priorRows.push({
    id: rule.id, label: rule.label,
    n: all.length,
    windows: primary.length,
    usableWindows: usable.length,
    mean: boot.mean,
    lo: boot.lo,
    hi: boot.hi,
    graduated: pass,
  });
}
lines.push(any ? 'At least one major rule cleared every usable week at 0.30%.' : 'No major rule graduated. They stay at exploration size.');
fs.writeFileSync('MAJORS_REPORT.md', lines.join('\n'));
const prior = {
  id: 'majors-v4',
  collectedAt: data.collectedAt || null,
  summary: any
    ? 'A pre-registered major-coin rule was positive on every usable week after a 0.30% round trip. That rule can use the normal paper size.'
    : 'No pre-registered major-coin rule was positive across three or more weeks after a 0.30% round trip. They stay at 1% exploration size.',
  edges: Object.fromEntries(priorRows.map((r) => [r.id, r.graduated])),
  rows: priorRows,
};
fs.writeFileSync('engine/majors-prior.js', `// Generated by runner/study-majors.mjs. Do not hand-edit the verdict.\nexport const MAJORS_PRIOR = ${JSON.stringify(prior, null, 2)};\n`);
console.log(JSON.stringify({ pools: pools.length, blocks: blocks.length, rows: priorRows }, null, 2));
